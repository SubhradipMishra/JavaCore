package Day1;

public class Ch2DataTypes {
    public static void main(String[] args) {
        

        //  Java data types define the type of data a variable can store in a program.
        /*
           Data types have two type -->
            i)   Premetive data type:- Store value simply in memory.(Int,Char,long,Short,byte,boolean)
            ii)  Non-Premetive data type:- Store memory reference to object.(String,Class,Object)

            

        */

            int a = 10 ; 
            boolean b = true;
            char ch = 'a';
            long ln = 100 ;

            System.out.println(a);
            System.out.println(b);
            System.out.println(ch);
            System.out.println(ln);

    }
}